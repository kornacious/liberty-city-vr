#!/usr/bin/env python3
"""Generate the embedded 48 kHz MIT KEMAR table from the unmodified public ZIP.

Requires numpy; no downloads occur here. See overlay/docs/SPATIAL_AUDIO.md.
"""
import argparse
import hashlib
import io
from pathlib import Path
import wave
import zipfile

import numpy as np

SHA256 = 'a48e73137390626ef1e45d1de6a4d98530c6aa570e71b40f7c4442241ed5fa22'
COUNTS = (56, 60, 72, 72, 72, 72, 72, 60, 56, 45, 36, 24, 12, 1)
TAPS = 144  # 128 samples at 44.1 kHz, resampled to 48 kHz and padded for SIMD.


def generate(archive):
    blob = archive.read_bytes()
    if hashlib.sha256(blob).hexdigest() != SHA256:
        raise ValueError('Unexpected MIT diffuse.zip checksum')
    responses = []
    rings = []
    with zipfile.ZipFile(io.BytesIO(blob)) as source:
        for ring, count in enumerate(COUNTS):
            elevation = -40 + 10 * ring
            rings.append((count, len(responses)))
            for index in range(count // 2 + 1):
                azimuth = round(index * 360 / count)
                name = f'elev{elevation}/H{elevation}e{azimuth:03}a.wav'
                with wave.open(io.BytesIO(source.read(name))) as wav:
                    assert (wav.getnchannels(), wav.getsampwidth(), wav.getframerate(), wav.getnframes()) == (2, 2, 44100, 128)
                    data = np.frombuffer(wav.readframes(128), dtype='<i2').reshape(128, 2).astype(float)
                # Bandlimited resampling. Scale by the input/output rate ratio
                # because these are FIR coefficients, preserving filter DC gain.
                distance = np.arange(TAPS)[:, None] * 44100 / 48000 - np.arange(128)[None, :]
                window = np.where(np.abs(distance) < 16, 0.5 + 0.5 * np.cos(np.pi * distance / 16), 0)
                result = (np.sinc(distance) * window) @ data * (44100 / 48000)
                responses.append(np.rint(result).clip(-32768, 32767).astype(np.int16).T)
    lines = ['// Generated by tools/generate-quest-hrtf.py; do not edit.',
             '// Copyright 1994 MIT Media Laboratory. Measurements: Bill Gardner and Keith Martin.',
             '// Attribution and source license: overlay/docs/SPATIAL_AUDIO.md.',
             'static constexpr Ring Rings[] = {']
    lines.extend(f'    {{{count}, {offset}}},' for count, offset in rings)
    lines.append('};\nstatic constexpr int16_t Responses[][2][Taps] = {')
    for response in responses:
        lines.append('    {')
        for ear in response:
            lines.append('        {' + ','.join(str(int(value)) for value in ear) + '},')
        lines.append('    },')
    lines.append('};\n')
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('archive', type=Path)
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'overlay/src/audio/QuestHrtfData.inc')
    args = parser.parse_args()
    args.output.write_text(generate(args.archive), encoding='utf-8', newline='\n')
